// Hoán vị: bit thứ i của đầu ra = bit thứ table[i] của đầu vào (đánh số từ 1, tính từ trái)
uint64_t permute(uint64_t in, int n_in, int *table, int n_out) {
    uint64_t out = 0;
    for (int i = 0; i < n_out; i++) {
        uint64_t bit = (in >> (n_in - table[i])) & 1;
        out |= bit << (n_out - 1 - i);
    }
    return out;
}

// Xoay trái số 28 bit
uint32_t rotate28(uint32_t x, int n) {
    return ((x << n) | (x >> (28 - n))) & 0x0FFFFFFF;
}

// Sinh 16 khóa con
void make_keys(uint64_t key, uint64_t K[16]) {
    uint64_t k56 = permute(key, 64, PC1, 56);
    uint32_t C = (k56 >> 28) & 0x0FFFFFFF;
    uint32_t D = k56 & 0x0FFFFFFF;
    printf("PC-1     = %014llX\n", k56);
    printf("C0       = %07X   D0 = %07X\n", C, D);
    for (int i = 0; i < 16; i++) {
        C = rotate28(C, SHIFTS[i]);
        D = rotate28(D, SHIFTS[i]);
        uint64_t CD = ((uint64_t)C << 28) | D;
        K[i] = permute(CD, 56, PC2, 48);
        printf("C%-2d      = %07X   D%-2d = %07X   K%-2d = %012llX\n", i + 1, C, i + 1, D, i + 1, K[i]);
    }
}

// Hàm F của mỗi vòng
uint32_t f(uint32_t R, uint64_t K) {
    uint64_t e = permute(R, 32, E, 48);
    uint64_t x = e ^ K;
    uint32_t s = 0;
    for (int i = 0; i < 8; i++) {
        int b = (x >> (42 - 6 * i)) & 0x3F;      // lấy 6 bit cho hộp S thứ i
        int row = ((b >> 4) & 2) | (b & 1);       // bit đầu và bit cuối
        int col = (b >> 1) & 0xF;                 // 4 bit giữa
        s = (s << 4) | S[i][row][col];
    }
    uint32_t p = permute(s, 32, P, 32);
    printf("  E(R)   = %012llX\n", e);
    printf("  E^K    = %012llX\n", x);
    printf("  S-box  = %08X\n", s);
    printf("  P      = %08X\n", p);
    return p;
}

uint64_t des_encrypt(uint64_t plain, uint64_t key) {
    uint64_t K[16];
    printf("--- Sinh khoa con ---\n");
    make_keys(key, K);

    printf("--- Ma hoa ---\n");
    uint64_t ip = permute(plain, 64, IP, 64);
    uint32_t L = ip >> 32;
    uint32_t R = ip & 0xFFFFFFFF;
    printf("IP       = %016llX\n", ip);
    printf("L0       = %08X   R0 = %08X\n", L, R);

    for (int i = 0; i < 16; i++) {
        printf("Vong %d:\n", i + 1);
        uint32_t temp = R;
        R = L ^ f(R, K[i]);
        L = temp;
        printf("  L%-2d    = %08X   R%-2d = %08X\n", i + 1, L, i + 1, R);
    }

    // Sau vòng 16 phải đổi chỗ L và R
    uint64_t pre = ((uint64_t)R << 32) | L;
    uint64_t c = permute(pre, 64, IP_INV, 64);
    printf("R16L16   = %016llX\n", pre);
    printf("IP^-1    = %016llX\n", c);
    return c;
}

